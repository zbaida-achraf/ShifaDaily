// Release signing is read from android/keystore.properties (git-ignored) or from
// environment variables. Nothing secret is stored in source control.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String, env: String): String? =
    keystoreProps.getProperty(key) ?: System.getenv(env)

val releaseStoreFile = signingValue("storeFile", "SHIFADAILY_STORE_FILE")

android {
    namespace = "com.shifadaily.app"
    // compileSdk 37 is required by current AndroidX releases; targetSdk stays at the Play-required 36.
    compileSdk = 37

    defaultConfig {
        applicationId = "com.shifadaily.app"
        // minSdk 26 (Android 8.0): notification channels and java.time are native,
        // and the platform still receives TLS 1.2+ / modern keystore support.
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        if (releaseStoreFile != null) {
            create("release") {
                storeFile = rootProject.file(releaseStoreFile)
                storePassword = signingValue("storePassword", "SHIFADAILY_STORE_PASSWORD")
                keyAlias = signingValue("keyAlias", "SHIFADAILY_KEY_ALIAS")
                keyPassword = signingValue("keyPassword", "SHIFADAILY_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release")
        }
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    androidResources {
        // Only ship the languages the app is translated into.
        localeFilters += listOf("en", "ar")
    }

    bundle {
        // The app switches language at runtime (no Play Core language download), so every
        // install must contain both English and Arabic resources.
        language { enableSplit = false }
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
}

